std::string to_ascii(std::string_view utf8) {
    std::string out;
    for (std::size_t i = 0; i < utf8.size();) {
        const auto b = static_cast<unsigned char>(utf8[i]);
        if (b < 0x80) {
            out += (b >= 32 && b < 127) ? static_cast<char>(b) : '?';
            ++i;
            continue;
        }
        const int length = b >= 0xF0 ? 4 : b >= 0xE0 ? 3 : b >= 0xC0 ? 2 : 1;
        unsigned code = 0;
        if (length == 2 && i + 1 < utf8.size()) {
            code = ((b & 0x1Fu) << 6) | (static_cast<unsigned char>(utf8[i + 1]) & 0x3Fu);
        }
        out += code >= 0xC0 && code <= 0xFF ? kLatin1[code - 0xC0] : '?';
        i += static_cast<std::size_t>(length);
    }
    return out;
}

void draw_text(Picture picture, int x, int y, std::string_view text, std::uint16_t color) {
    for (const char ch : text) {
        const int index = (ch >= 32 && ch < 127) ? ch - 32 : '?' - 32;
        for (int row = 0; row < 7; ++row) {
            const int py = y + row;
            if (py < 0 || py >= kHeight) continue;
            for (int col = 0; col < 5; ++col) {
                const int px = x + col;
                if (px < 0 || px >= kWidth || !((kFont[index][row] >> (4 - col)) & 1)) continue;
                picture[static_cast<std::size_t>(py) * kWidth + static_cast<std::size_t>(px)] = color;
            }
        }
        x += kCellWidth;
    }
}

void shade(Picture picture, int x, int y, int width, int height) {
    const int x0 = std::max(x, 0), x1 = std::min(x + width, kWidth);
    const int y0 = std::max(y, 0), y1 = std::min(y + height, kHeight);
    for (int py = y0; py < y1; ++py) {
        for (int px = x0; px < x1; ++px) {
            std::uint16_t& p = picture[static_cast<std::size_t>(py) * kWidth + static_cast<std::size_t>(px)];
            p = static_cast<std::uint16_t>((p >> 2) & 0x1CE7);  // each 5-bit channel / 4
        }
    }
}

void Osd::show(std::string text, int frames, std::string_view replaces) {
    if (echo_) {
        std::printf("osd: %s\n", text.c_str());
        std::fflush(stdout);
    }
    if (!replaces.empty()) {
        const std::string prefix = to_ascii(replaces);
        std::erase_if(messages_, [&](const Message& m) { return m.text.starts_with(prefix); });
    }
    messages_.push_back({to_ascii(text), frames});
    while (messages_.size() > 4) {
        messages_.pop_front();
    }
}

void Osd::tick() {
    for (Message& m : messages_) {
        --m.frames_left;
    }
    while (!messages_.empty() && messages_.front().frames_left <= 0) {
        messages_.pop_front();
    }
}

void Osd::draw(Picture picture) const {
    int y = kHeight - kCellHeight * static_cast<int>(messages_.size()) - 2;
    for (const Message& m : messages_) {
        const std::string_view text = std::string_view(m.text).substr(0, kColumns - 1);
        shade(picture, 0, y - 1, static_cast<int>(text.size()) * kCellWidth + 3, kCellHeight);
        draw_text(picture, 2, y, text, color::kWhite);
        y += kCellHeight;
    }
}

