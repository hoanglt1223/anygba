#include "codegen/c_emitter.h"

#include <algorithm>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <stdexcept>

// The generated program: one header with every prototype, the functions split across
// shard files so builds parallelise, the sorted dispatch table, and a CMake project that
// links the installed runtime.
namespace anygba::codegen {

namespace {

void write_file(const std::filesystem::path& path, const std::string& text, std::vector<std::filesystem::path>& written) {
    // Leave unchanged files alone so build systems do not recompile them.
    {
        std::ifstream existing(path, std::ios::binary);
        if (existing) {
            const std::string old{std::istreambuf_iterator<char>(existing), std::istreambuf_iterator<char>()};
            if (old == text) {
                written.push_back(path);
                return;
            }
        }
    }
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    if (!out) {
        throw std::runtime_error("cannot write " + path.string());
    }
    out << text;
    if (!out) {
        throw std::runtime_error("write failed: " + path.string());
    }
    written.push_back(path);
}

std::string c_string(const std::string& s) {
    std::string out = "\"";
    for (const char ch : s) {
        if (ch == '"' || ch == '\\') {
            out += '\\';
            out += ch;
        } else if (static_cast<unsigned char>(ch) < 0x20 || static_cast<unsigned char>(ch) > 0x7E) {
            char buf[8];
            std::snprintf(buf, sizeof buf, "\\%03o", static_cast<unsigned char>(ch));
            out += buf;
        } else {
            out += ch;
        }
    }
    return out + "\"";
}

}  // namespace

std::vector<std::filesystem::path> write_project(const std::filesystem::path& dir, const analysis::Image& image,
                                                 const analysis::Discovery& discovery, const ProjectInfo& info) {
    std::filesystem::create_directories(dir);
    std::vector<std::filesystem::path> written;
    const auto& functions = discovery.functions;

    std::string header = "/* Generated by anygba-recomp. Do not edit. */\n#ifndef ANYGBA_GAME_H\n#define ANYGBA_GAME_H\n\n"
                         "#include <anygba/cpu.h>\n\n";
    for (const auto& [addr, fn] : functions) {
        header += "void " + function_name(addr) + "(anygba_cpu* c);\n";
    }
    for (const auto& [addr, name] : info.replacements) {
        if (!functions.contains(addr)) {
            char buf[64];
            std::snprintf(buf, sizeof buf, "replacement for 0x%08x: no function starts there", addr);
            throw std::runtime_error(buf);
        }
        header += "void " + name + "(anygba_cpu* c); /* hand-written replacement */\n";
    }
    for (const auto& o : info.overrides) {
        char buf[64];
        const auto fn = functions.find(o.addr);
        if (fn == functions.end()) {
            std::snprintf(buf, sizeof buf, "override for 0x%08x: no function starts there", o.addr);
            throw std::runtime_error(buf);
        }
        if ((fn->second.mode == analysis::Mode::Thumb) != o.thumb) {
            std::snprintf(buf, sizeof buf, "override for 0x%08x: the function there is %s code", o.addr,
                          o.thumb ? "ARM" : "Thumb");
            throw std::runtime_error(buf);
        }
        if (info.replacements.contains(o.addr)) {
            std::snprintf(buf, sizeof buf, "0x%08x has both [[replace]] and [[override]]", o.addr);
            throw std::runtime_error(buf);
        }
        header += "void " + function_name(o.addr) + "_orig(anygba_cpu* c); /* translation behind an override */\n";
        header += "extern uint32_t " + function_name(o.addr) + "_hits[]; /* its blocks run, for difftests */\n";
        header += "extern const uint32_t " + function_name(o.addr) + "_blocks[];\n";
    }
    if (!info.overrides.empty()) {
        header += "extern uint8_t ag_override_on[];\n";
    }
    header += "\n#endif\n";
    write_file(dir / "game.h", header, written);

    const std::size_t shards = info.shards ? info.shards : std::max<std::size_t>(1, (functions.size() + 499) / 500);
    std::vector<std::string> shard_text(shards, "/* Generated by anygba-recomp. Do not edit. */\n#include \"game.h\"\n\n");
    EmitOptions options;
    options.image = &image;
    options.functions = &functions;
    std::map<std::uint32_t, std::size_t> override_index;
    std::map<std::uint32_t, std::size_t> override_blocks;  // addr -> number of blocks
    for (std::size_t k = 0; k < info.overrides.size(); ++k) override_index[info.overrides[k].addr] = k;
    std::size_t i = 0;
    for (const auto& [addr, fn] : functions) {
        std::string& shard = shard_text[i * shards / std::max<std::size_t>(functions.size(), 1)];
        if (const auto ov = override_index.find(addr); ov != override_index.end()) {
            // Every call path (direct calls, the dispatcher, the interpreter) enters f_XXXXXXXX.
            const std::string name = function_name(addr);
            const std::string k = std::to_string(ov->second) + "u";
            EmitOptions original = options;
            original.name = name + "_orig";
            std::vector<std::uint32_t> blocks;
            original.coverage = name + "_hits";
            original.blocks = &blocks;
            const std::string body = emit_function(fn, original);
            const std::string size = std::to_string(std::max<std::size_t>(blocks.size(), 1));  // ISO C: no empty arrays
            shard += "uint32_t " + name + "_hits[" + size + "];\nconst uint32_t " + name + "_blocks[" + size + "] = {";
            if (blocks.empty()) shard += "0";
            for (std::size_t b = 0; b < blocks.size(); ++b) {
                char buf[16];
                std::snprintf(buf, sizeof buf, "%s0x%08xu", b ? ", " : "", blocks[b]);
                shard += buf;
            }
            shard += "};\n\n" + body + "\n";
            override_blocks[addr] = blocks.size();
            shard += "void " + name + "(anygba_cpu* c) {\n    if (ag_override_on[" + std::to_string(ov->second) +
                     "]) {\n        anygba_override_run(c, " + k + ");\n        return;\n    }\n    " + name +
                     "_orig(c);\n}\n\n";
        } else if (const auto rep = info.replacements.find(addr); rep != info.replacements.end()) {
            // Direct calls from other generated functions land here too.
            shard += "void " + function_name(addr) + "(anygba_cpu* c) { " + rep->second + "(c); }\n\n";
        } else {
            shard += emit_function(fn, options) + "\n";
        }
        ++i;
    }
    // Shards from an earlier run with more of them would be compiled in too.
    for (std::size_t s = shards;; ++s) {
        char name[32];
        std::snprintf(name, sizeof name, "funcs_%03zu.c", s);
        if (!std::filesystem::remove(dir / name)) break;
    }
    for (std::size_t s = 0; s < shards; ++s) {
        char name[32];
        std::snprintf(name, sizeof name, "funcs_%03zu.c", s);
        if (shard_text[s].find("void f_") == std::string::npos) {
            shard_text[s] += "typedef int anygba_empty_shard;\n";  // ISO C needs a declaration
        }
        write_file(dir / name, shard_text[s], written);
    }

    std::string dispatch = "/* Generated by anygba-recomp. Do not edit. */\n#include \"game.h\"\n\n"
                           "static const anygba_function_entry functions[] = {\n";
    for (const auto& [addr, fn] : functions) {
        // A hand-written replacement does not read the ROM code, so patches never bypass it.
        const analysis::AddressRange code =
            info.replacements.contains(addr) ? analysis::AddressRange{} : code_footprint(fn, &image);
        // RAM code runs only while RAM holds the ROM bytes it was compiled from.
        std::uint32_t source = 0;
        if (!analysis::Image::is_rom(addr) && code.end > code.begin) {
            if (const auto off = image.rom_offset(code.begin, code.end - code.begin)) {
                source = analysis::kRomBase + *off;
            }
        }
        char buf[160];
        std::snprintf(buf, sizeof buf, "    {0x%08xu, %d, %s, 0x%08xu, 0x%08xu, 0x%08xu},\n", addr,
                      fn.mode == analysis::Mode::Thumb ? 1 : 0, function_name(addr).c_str(), code.begin, code.end,
                      source);
        dispatch += buf;
    }
    if (functions.empty()) {
        dispatch += "    {0, 0, 0, 0, 0, 0},\n";
    }
    dispatch += "};\n\n";
    if (!info.overrides.empty()) {
        dispatch += "uint8_t ag_override_on[" + std::to_string(info.overrides.size()) +
                    "];\n\nstatic const anygba_override_entry overrides[] = {\n";
        for (const auto& o : info.overrides) {
            char buf[32];
            std::snprintf(buf, sizeof buf, "0x%08xu, %d, ", o.addr, o.thumb ? 1 : 0);
            dispatch += "    {" + std::string(buf) + c_string(o.impl) + ", " + c_string(o.name) + ", " +
                        c_string(o.engine) + ", " + (o.enabled ? "1" : "0") + ", " + function_name(o.addr) + "_orig, " +
                        (o.verified ? "1" : "0") + ", " + function_name(o.addr) + "_hits, " + function_name(o.addr) +
                        "_blocks, " + std::to_string(override_blocks[o.addr]) + "u},\n";
        }
        dispatch += "};\n\n";
    }
    dispatch += "const anygba_game anygba_game_info = {\n    " + c_string(info.title) + ",\n    \"" + info.rom_sha256 +
                "\",\n    " + std::to_string(info.rom_size) + "u,\n    functions,\n    " +
                std::to_string(functions.size()) + "u,\n    " + c_string(info.save_type) + ",\n    " +
                std::to_string(info.rtc) + ",\n    " + c_string(info.video) + ",\n";
    if (!info.overrides.empty()) {
        dispatch += "    overrides,\n    " + std::to_string(info.overrides.size()) + "u,\n    ag_override_on,\n";
    }
    dispatch += "};\n";
    write_file(dir / "dispatch.c", dispatch, written);

    std::string cmake =
        "# Generated by anygba-recomp. Build with:\n"
        "#   cmake -S . -B out -DCMAKE_PREFIX_PATH=<anygba install prefix> && cmake --build out --config Release\n"
        "cmake_minimum_required(VERSION 3.28)\n"
        "project(anygba_game C CXX)\n"
        "find_package(anygba REQUIRED CONFIG)\n"
        "file(GLOB game_sources CONFIGURE_DEPENDS \"${CMAKE_CURRENT_SOURCE_DIR}/*.c\")\n"
        "add_executable(game ${game_sources})\n"
        "target_link_libraries(game PRIVATE anygba::game_main)\n";
    const bool cpp = std::any_of(info.sources.begin(), info.sources.end(),
                                 [](const std::filesystem::path& p) { return p.extension() == ".cpp"; });
    if (cpp) {
        // C++ override modules (docs/dev/OVERRIDES.md).
        cmake += "file(GLOB game_cpp_sources CONFIGURE_DEPENDS \"${CMAKE_CURRENT_SOURCE_DIR}/*.cpp\")\n"
                 "target_sources(game PRIVATE ${game_cpp_sources})\n"
                 "target_compile_features(game PRIVATE cxx_std_20)\n"
                 // No modules here; scanning needs clang-scan-deps, which Linux clang packages often lack.
                 "set_target_properties(game PROPERTIES CXX_SCAN_FOR_MODULES OFF)\n";
    }
    write_file(dir / "CMakeLists.txt", cmake, written);
    for (const auto& source : info.sources) {
        if (const auto clash = std::find_if(info.sources.begin(), info.sources.end(),
                                            [&](const std::filesystem::path& p) {
                                                return &p != &source && p.filename() == source.filename();
                                            });
            clash != info.sources.end()) {
            throw std::runtime_error("two sources share the file name " + source.filename().string() + ": " +
                                     source.string() + " and " + clash->string());
        }
        std::ifstream in(source, std::ios::binary);
        if (!in) {
            throw std::runtime_error("cannot read " + source.string());
        }
        write_file(dir / source.filename(), std::string{std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()},
                   written);
    }
    return written;
}

}  // namespace anygba::codegen
