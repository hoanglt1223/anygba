// Writes the C fixture for the codegen differential tests: one generated function per
// sampled ARM and Thumb instruction, plus a table the tests walk. Run by the build.
#include "codegen/c_emitter.h"
#include "decode/arm.h"
#include "decode/thumb.h"

#include <cstdio>
#include <fstream>
#include <random>
#include <string>

using namespace anygba;
using decode::Insn;
using decode::Op;

namespace {

constexpr std::uint32_t kArmBase = 0x08001000;
constexpr std::uint32_t kThumbBase = 0x08100000;
constexpr int kPerSet = 8192;

// Instructions whose generated code leaves the instruction itself (direct calls through
// the dispatcher, BIOS calls) or never terminates (branch to self) are tested end to end
// by the ROM tests instead.
bool testable(const Insn& in) {
    switch (in.op) {
    case Op::UNDEFINED:
    case Op::BL:
    case Op::BL_LO:
    case Op::SWI:
        return false;
    case Op::B:
        return in.imm_value != in.addr;
    default:
        return true;
    }
}

}  // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fputs("usage: anygba-codegen-fixture <out.c>\n", stderr);
        return 2;
    }
    std::mt19937 rng(0xC0DE6E4);
    std::string functions;
    std::string table = "const anygba_fixture_entry anygba_fixture[] = {\n";
    int count = 0;

    const auto add = [&](const Insn& in) {
        analysis::Function fn;
        fn.entry = in.addr;
        fn.mode = in.thumb ? analysis::Mode::Thumb : analysis::Mode::Arm;
        fn.insns.emplace(in.addr, in);
        fn.labels.insert(in.addr);
        codegen::EmitOptions options;
        options.name = "fx_" + std::to_string(count);
        functions += codegen::emit_function(fn, options) + "\n";
        char row[96];
        std::snprintf(row, sizeof row, "    {0x%08xu, 0x%08xu, %d, fx_%d},\n", in.raw, in.addr, in.thumb ? 1 : 0, count);
        table += row;
        ++count;
    };

    // ARM: spread samples over the 4096 classes selected by bits 27-20 and 7-4.
    for (int i = 0; i < kPerSet;) {
        const std::uint32_t cls = static_cast<std::uint32_t>(i) % 4096;
        std::uint32_t w = rng();
        w = (w & 0xF00FFF0Fu) | ((cls >> 4) << 20) | ((cls & 0xF) << 4);
        if ((w >> 28) == 0xF) {
            w &= 0xEFFFFFFFu;
        }
        const Insn in = decode::decode_arm(w, kArmBase + 4u * static_cast<std::uint32_t>(i));
        if (testable(in)) {
            add(in);
            ++i;
        } else if ((rng() & 7) == 0) {
            ++i;  // some classes have no testable encodings; do not loop forever on them
        }
    }
    for (int i = 0; i < kPerSet;) {
        const auto h = static_cast<std::uint16_t>(rng());
        const Insn in = decode::decode_thumb(h, kThumbBase + 2u * static_cast<std::uint32_t>(i));
        if (testable(in)) {
            add(in);
            ++i;
        }
    }
    table += "};\nconst unsigned anygba_fixture_count = " + std::to_string(count) + "u;\n";

    std::ofstream out(argv[1], std::ios::binary | std::ios::trunc);
    out << "/* Generated by anygba-codegen-fixture. */\n#include <anygba/cpu.h>\n#include \"support/codegen_fixture.h\"\n\n"
        << functions << table;
    if (!out) {
        std::fprintf(stderr, "cannot write %s\n", argv[1]);
        return 1;
    }
    return 0;
}
